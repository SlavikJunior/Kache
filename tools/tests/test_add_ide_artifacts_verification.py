class InvariantTests(Fixture):
    def test_second_run_is_a_no_op(self) -> None:
        self.put("org.example", "lib", "3.0", {"lib-3.0-sources.jar": b"s"})
        self.run_tool(("lib-3.0-sources.jar", "org.example:lib:3.0"))
        first = self.metadata()
        code, out = self.run_tool(("lib-3.0-sources.jar", "org.example:lib:3.0"))
        self.assertEqual(code, tool.EXIT_OK)
        self.assertEqual(self.metadata(), first)
        self.assertIn("добавлено: 0", out)

    def test_no_duplicate_artifact_entries(self) -> None:
        self.put("org.example", "lib", "3.0", {"lib-3.0-sources.jar": b"s"})
        self.run_tool(("lib-3.0-sources.jar", "org.example:lib:3.0"))
        self.run_tool(("lib-3.0-sources.jar", "org.example:lib:3.0"))
        self.assertEqual(self.metadata().count('<artifact name="lib-3.0-sources.jar">'), 1)

    def test_existing_entries_are_preserved_byte_for_byte(self) -> None:
        self.put("org.example", "lib", "1.0", {"lib-1.0-sources.jar": b"s"})
        self.run_tool(("lib-1.0-sources.jar", "org.example:lib:1.0"))
        # Существующий артефакт той же компоненты сохранён строка в строку.
        existing_artifact = (
            '         <artifact name="lib-1.0.jar">\n'
            '            <sha256 value="aaaa" origin="Generated by Gradle"/>\n'
            "         </artifact>\n"
        )
        self.assertIn(existing_artifact, self.metadata())

    def test_component_order_is_never_changed(self) -> None:
        self.put("org.zzz", "late", "1.0", {"late-1.0-sources.jar": b"s"})
        self.put("org.aaa", "early", "1.0", {"early-1.0-sources.jar": b"s"})
        before = [m.group(1) for m in re.finditer(r'<component group="([^"]+)"', self.metadata())]
        self.run_tool(("late-1.0-sources.jar", "org.zzz:late:1.0"),
                      ("early-1.0-sources.jar", "org.aaa:early:1.0"))
        after = [m.group(1) for m in re.finditer(r'<component group="([^"]+)"', self.metadata())]
        self.assertEqual(before, after)

    def test_file_structure_is_valid_xml(self) -> None:
        import xml.etree.ElementTree as ET
        self.put("org.example", "lib", "4.0", {"lib-4.0-sources.jar": b"s"})
        self.run_tool(("lib-4.0-sources.jar", "org.example:lib:4.0"))
        ET.fromstring(self.metadata())

    def test_file_ends_with_single_newline(self) -> None:
        self.put("org.example", "lib", "5.0", {"lib-5.0-sources.jar": b"s"})
        self.run_tool(("lib-5.0-sources.jar", "org.example:lib:5.0"))
        self.assertTrue(self.metadata().endswith("</verification-metadata>\n"))


class RegressionTests(Fixture):
    """Классы ошибок, найденные при Sync с Groovy 4.0.32 (встроенная библиотека Gradle).

    Версия встроенной библиотеки меняется вместе с дистрибутивом Gradle. Метаданные помнят
    старую версию (4.0.29), а IDE при Sync запрашивает sources новой (4.0.32), для которой
    ни `.module`, ни checksum ещё не записаны.
    """

    def _record_like_gradle(self, group: str, name: str, version: str, files: dict[str, bytes]) -> None:
        """Файлы в кэше плюс запись дескриптора, какую оставил бы Gradle."""
        directory = self.cache / group / name / version / "a1b2c3"
        directory.mkdir(parents=True, exist_ok=True)
        for filename, data in files.items():
            (directory / filename).write_bytes(data)
        module = {"formatVersion": "1.1", "variants": [{"name": "sourcesElements", "files": [
            {"name": f"{name}-{version}-sources.jar", "sha256": sha(files[f"{name}-{version}-sources.jar"])},
        ]}]}
        module_bytes = json.dumps(module).encode()
        (directory / f"{name}-{version}.module").write_bytes(module_bytes)
        self.meta.write_text(
            self.metadata().replace("   </components>\n", (
                f'      <component group="{group}" name="{name}" version="{version}">\n'
                f'         <artifact name="{name}-{version}.module">\n'
                f'            <sha256 value="{sha(module_bytes)}" origin="Generated by Gradle"/>\n'
                "         </artifact>\n"
                "      </component>\n"
                "   </components>\n")),
            encoding="utf-8",
        )

    def test_new_version_of_embedded_library_is_not_written_without_descriptor(self) -> None:
        # Компонента есть в метаданных, но в другой версии (4.0.29). Версии 4.0.32 и её
        # .module нет: инструмент не имеет права записать её sources сам.
        self.put("org.apache.groovy", "groovy", "4.0.29", {"groovy-4.0.29-sources.jar": b"old"})
        self.put("org.apache.groovy", "groovy", "4.0.32", {"groovy-4.0.32-sources.jar": b"new"}, seeded=False)
        before = self.metadata()
        code, out = self.run_tool(("groovy-4.0.32-sources.jar", "org.apache.groovy:groovy:4.0.32"))
        self.assertEqual(code, tool.EXIT_SKIPPED, out)
        self.assertIn("без дескриптора", out)
        self.assertEqual(self.metadata(), before)

    def test_module_descriptor_is_never_written_by_tool(self) -> None:
        # Сам `.module` подтвердить нечем: его sha256 даёт только скачивание Gradle.
        self.put("org.apache.groovy", "groovy", "4.0.32", {"groovy-4.0.32-sources.jar": b"s"}, seeded=False)
        before = self.metadata()
        code, out = self.run_tool(("groovy-4.0.32.module", "org.apache.groovy:groovy:4.0.32"))
        self.assertEqual(code, tool.EXIT_SKIPPED, out)
        self.assertIn("записывает только Gradle", out)
        self.assertEqual(self.metadata(), before)

    def test_documentation_recorded_once_gradle_descriptor_confirms_it(self) -> None:
        # Тот же случай, но дескриптор 4.0.32 уже записан Gradle: теперь sources проверяется
        # по его sha256 и записывается.
        data = b"groovy sources content"
        self._record_like_gradle("org.apache.groovy", "groovy", "4.0.32",
                                 {"groovy-4.0.32-sources.jar": data})
        code, out = self.run_tool(("groovy-4.0.32-sources.jar", "org.apache.groovy:groovy:4.0.32"))
        self.assertEqual(code, tool.EXIT_OK, out)
        self.assertIn(f'<sha256 value="{sha(data)}" origin="{tool.ORIGIN}"/>', self.metadata())

    def test_repository_label_does_not_change_the_decision(self) -> None:
        # Репозиторий «Gradle Libs» (не Google и не Central) решает не больше, чем любой
        # другой: с подтверждением — записываем, без подтверждения — отказываем.
        data = b"from gradle libs"
        self._record_like_gradle("org.apache.groovy", "groovy", "4.0.32",
                                 {"groovy-4.0.32-sources.jar": data})
        log = self.root / "idea-gradle-libs.log"
        log.write_text(
            "1 artifacts failed verification:\n"
            "  - groovy-4.0.32-sources.jar (org.apache.groovy:groovy:4.0.32) from repository Gradle Libs\n",
            encoding="utf-8",
        )
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            code = tool.main(["--log", str(log), "--report", str(self.report([])),
                              "--metadata", str(self.meta), "--cache", str(self.cache)])
        self.assertEqual(code, tool.EXIT_OK, out.getvalue())
        self.assertIn(f'<sha256 value="{sha(data)}"', self.metadata())

    def test_repository_label_without_confirmation_is_refused(self) -> None:
        self.put("org.apache.groovy", "groovy", "4.0.32", {"groovy-4.0.32-sources.jar": b"x"}, seeded=False)
        # Дескриптора нет вовсе, так что подтверждения не будет независимо от репозитория.
        code, out = self.run_tool(("groovy-4.0.32-sources.jar", "org.apache.groovy:groovy:4.0.32"))
        self.assertEqual(code, tool.EXIT_SKIPPED)
        self.assertNotIn("groovy-4.0.32-sources.jar", self.metadata())

    def test_repeated_run_after_gradle_record_is_stable(self) -> None:
        data = b"stable"
        self._record_like_gradle("org.apache.groovy", "groovy", "4.0.32",
                                 {"groovy-4.0.32-sources.jar": data})
        self.run_tool(("groovy-4.0.32-sources.jar", "org.apache.groovy:groovy:4.0.32"))
        first = self.metadata()
        self.run_tool(("groovy-4.0.32-sources.jar", "org.apache.groovy:groovy:4.0.32"))
        self.assertEqual(self.metadata(), first)



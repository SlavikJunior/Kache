HEADER = (
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">\n'
    "   <configuration>\n"
    "      <verify-metadata>true</verify-metadata>\n"
    "      <verify-signatures>false</verify-signatures>\n"
    "   </configuration>\n"
    "   <components>\n"
)
FOOTER = "   </components>\n</verification-metadata>\n"
EXISTING = (
    '      <component group="org.example" name="lib" version="1.0">\n'
    '         <artifact name="lib-1.0.jar">\n'
    '            <sha256 value="aaaa" origin="Generated by Gradle"/>\n'
    "         </artifact>\n"
    '         <artifact name="lib-1.0.module">\n'
    '            <sha256 value="bbbb" origin="Generated by Gradle"/>\n'
    "         </artifact>\n"
    "      </component>\n"
)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class Fixture(unittest.TestCase):
    """Фейковый кэш Gradle, метаданные и отчёт во временном каталоге."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self._tmp.name)
        self.cache = self.root / "cache"
        self.cache.mkdir()
        self.meta = self.root / "verification-metadata.xml"
        self.meta.write_text(HEADER + EXISTING + FOOTER, encoding="utf-8")

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def seed(self, group: str, name: str, version: str) -> None:
        """Записывает компоненту с дескриптором `.module`, как это делает Gradle."""
        marker = f'<component group="{group}" name="{name}" version="{version}">'
        if marker in self.metadata():
            return
        block = (
            f"      {marker}\n"
            f'         <artifact name="{name}-{version}.module">\n'
            f'            <sha256 value="{"f" * 64}" origin="Generated by Gradle"/>\n'
            "         </artifact>\n"
            "      </component>\n"
        )
        self.meta.write_text(self.metadata().replace("   </components>\n", block + "   </components>\n"),
                             encoding="utf-8")

    def put(self, group: str, name: str, version: str, files: dict[str, bytes],
            gmm: bool = True, gmm_sha: dict[str, str] | None = None, module_name: str | None = None,
            seeded: bool = True) -> None:
        """Кладёт файлы в каталог модуля. gmm=True — рядом `.module` с sha256 файлов.
        seeded=True — компонента уже есть в metadata с дескриптором (обычный случай)."""
        if seeded:
            self.seed(group, name, version)
        module_name = module_name or name
        directory = self.cache / group / module_name / version / "a1b2c3"
        directory.mkdir(parents=True, exist_ok=True)
        for filename, data in files.items():
            (directory / filename).write_bytes(data)
        if gmm:
            entries = [
                {"name": f, "url": f, "sha256": (gmm_sha or {}).get(f, sha(d))}
                for f, d in files.items()
            ]
            module = {"formatVersion": "1.1", "variants": [{"name": "v", "files": entries}]}
            (directory / f"{module_name}-{version}.module").write_text(json.dumps(module))

    def report(self, rows: list[tuple[str, str]]) -> pathlib.Path:
        body = "".join(
            f'<tr><td class="uk-text-nowrap">{coords}</td>'
            f'<td><a href="file:/x/{filename}">{filename}</a></td>'
            f"<td><span>Checksums are missing from verification metadata</span></td></tr>\n"
            for filename, coords in rows
        )
        path = self.root / "report.html"
        path.write_text(f"<html><body><table>{body}</table></body></html>", encoding="utf-8")
        return path

    def run_tool(self, *requests: tuple[str, str]) -> tuple[int, str]:
        report = self.report(list(requests))
        # Пустой лог обязателен: иначе инструмент подхватит реальный idea.log машины.
        empty_log = self.root / "idea.log"
        empty_log.write_text("", encoding="utf-8")
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            code = tool.main(["--report", str(report), "--log", str(empty_log),
                              "--metadata", str(self.meta), "--cache", str(self.cache)])
        return code, out.getvalue()

    def metadata(self) -> str:
        return self.meta.read_text(encoding="utf-8")


class ParsingTests(unittest.TestCase):
    def test_report_row_with_android_module_keeps_requested_coordinates(self) -> None:
        # Реальная форма строки: файл samples-sources принадлежит платформенному модулю.
        row = (
            '<tr><td class="uk-text-nowrap">androidx.compose.animation:animation-android:1.12.1</td>'
            '<td><a href="file:/c/animation-1.12.1-samples-sources.jar">animation-1.12.1-samples-sources.jar</a></td>'
            "<td><span>Checksums are missing from verification metadata</span></td></tr>"
        )
        self.assertEqual(
            tool.parse_report(row),
            {tool.Request("animation-1.12.1-samples-sources.jar", "androidx.compose.animation",
                          "animation-android", "1.12.1")},
        )

    def test_mismatch_rows_are_not_requests(self) -> None:
        row = (
            '<tr><td>org.example:lib:1.0</td><td><a href="x">lib-1.0-sources.jar</a></td>'
            "<td><span>Checksum mismatch</span></td></tr>"
        )
        self.assertEqual(tool.parse_report(row), set())

    def test_log_block_with_multiple_failures(self) -> None:
        log = (
            "2 artifacts failed verification:\n"
            "  - a-1.0-javadoc.jar (org.example:a:1.0) from repository MavenRepo\n"
            "  - kotlin-stdlib-2.4.20-common-sources.jar (org.jetbrains.kotlin:kotlin-stdlib:2.4.20) x\n"
        )
        self.assertEqual(len(tool.parse_log(log)), 2)


